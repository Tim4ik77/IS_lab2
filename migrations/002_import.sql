BEGIN;

ALTER TABLE ticket ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS import_operation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    added_count INTEGER,
    started_at TIMESTAMP NOT NULL,
    finished_at TIMESTAMP,
    error TEXT
);
CREATE INDEX IF NOT EXISTS import_operation_user_id ON import_operation(username, id DESC);

-- Native updates must participate in the same optimistic version protocol as JPA.
CREATE OR REPLACE FUNCTION sell_ticket(p_ticket_id BIGINT, p_person_id BIGINT, p_amount INTEGER)
RETURNS BIGINT LANGUAGE plpgsql AS $$
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Сумма продажи должна быть больше 0' USING ERRCODE = '22023';
    END IF;
    IF p_person_id IS NULL OR NOT EXISTS (SELECT 1 FROM person WHERE id = p_person_id) THEN
        RAISE EXCEPTION 'Человек не найден' USING ERRCODE = 'P0002';
    END IF;
    UPDATE ticket SET person_id = p_person_id, price = p_amount, version = version + 1 WHERE id = p_ticket_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Билет не найден' USING ERRCODE = 'P0002'; END IF;
    RETURN p_ticket_id;
END;
$$;
COMMIT;
